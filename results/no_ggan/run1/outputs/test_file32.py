class FakeChannel:
    site = attr.ib()
    _reactor = attr.ib()
    result = attr.ib(factory=dict)
    _producer = attr.ib(default=None)
    @property
    def json_body(self):
        if not self.result:
            raise RuntimeError("Result is empty")
        body = self.result.get("body", b"")
        return json.loads(body.decode('utf-8'))
    @property
    def code(self):
        if not self.result:
            raise RuntimeError("Result is empty")
        return int(self.result.get("code", 0))
    @property
    def headers(self):
        if not self.result:
            raise RuntimeError("Result is empty")
        hdrs = self.result.get("headers", [])
        return Headers(dict(hdrs))
    def writeHeaders(self, code, message, hdrs):
        self.result["code"] = code
        self.result["headers"] = [(k, v) for k, v in hdrs.getAllRawHeaders()]
    def write(self, data):
        self.result.setdefault("body", b"")
        self.result["body"] += data
    def registerProducer(self, producer, streaming):
        self._producer = producer
        def resume():
            if self._producer:
                self._producer.resumeProducing()
                self._reactor.callLater(0.01, resume)
        self._reactor.callLater(0.01, resume)
    def unregisterProducer(self):
        self._producer = None
    def requestDone(self, _):
        pass
    def getPeer(self):
        return address.IPv4Address('TCP', '127.0.0.1', 12345)
    def getHost(self):
        return address.IPv4Address('TCP', '127.0.0.1', 80)
    @property
    def transport(self):
        return self
