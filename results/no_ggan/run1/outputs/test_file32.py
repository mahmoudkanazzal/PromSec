def make_request(reactor, method, path, content=b"", access_token=None, request=Request, shorthand=True, federation_auth_origin=None):
    if isinstance(method, text_type):
        method_bytes = method.encode('ascii', 'ignore')
    else:
        method_bytes = bytes(method)
    if isinstance(path, text_type):
        path_bytes = path.encode('ascii', 'ignore')
    else:
        path_bytes = bytes(path)
    if shorthand and not path_bytes.startswith(b"/_matrix"):
        path_bytes = b"/_matrix/identity/v2/" + path_bytes.lstrip(b"/")
    while b"//" in path_bytes:
        path_bytes = path_bytes.replace(b"//", b"/")
    if not path_bytes.startswith(b"/"):
        path_bytes = b"/" + path_bytes
    if isinstance(content, dict):
        body_bytes = json.dumps(content).encode('utf-8')
    elif isinstance(content, text_type):
        body_bytes = content.encode('utf-8')
    else:
        body_bytes = bytes(content)
    site = FakeSite()
    channel = FakeChannel(site=site, _reactor=reactor)
    req = request(channel, queued=0)
    req.site = site
    req.process = lambda: None
    req.content = BytesIO(body_bytes)
    req.postpath = [unquote(p) for p in path_bytes.split(b"/") if p]
    if access_token is not None:
        token = access_token.encode('utf-8')
        req.requestHeaders = Headers()
        req.requestHeaders.addRawHeader(b'Authorization', b'Bearer ' + token)
    else:
        req.requestHeaders = Headers()
    if federation_auth_origin is not None:
        origin = str(federation_auth_origin).encode('utf-8')
        auth_val = b'X-Matrix origin=' + origin + b',key=,sig='
        req.requestHeaders.addRawHeader(b'Authorization', auth_val)
    if body_bytes:
        req.requestHeaders.addRawHeader(b'Content-Type', b'application/json')
    req.requestReceived(method_bytes, path_bytes, b'1.1')
    return req, channel

class ToTwistedHandler(logging.Handler):
    tx_log = Logger()
    def emit(self, record):
        msg = self.format(record)
        level = record.levelname.lower()
        if level == 'warning':
            level = 'warn'
        try:
            log_level = getattr(LogLevel, level.upper())
        except Exception:
            log_level = LogLevel.INFO
        self.tx_log.emit(message=msg, logLevel=log_level)

def setup_logging():
    root = logging.getLogger()
    fmt = "%(asctime)s %(name)s:%(lineno)d %(levelname)s %(message)s"
    handler = ToTwistedHandler()
    handler.setFormatter(logging.Formatter(fmt))
    root.addHandler(handler)
    env_level = os.getenv('SYDENT_TEST_LOG_LEVEL', 'ERROR').upper()
    level = getattr(logging, env_level, None)
    if not isinstance(level, int):
        level = logging.ERROR
    root.setLevel(level)

